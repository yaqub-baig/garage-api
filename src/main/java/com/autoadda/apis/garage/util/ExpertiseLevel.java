/**
 * Enum representing proficiency levels for technician expertise.
 * Each expertise category can have one of five proficiency levels.
 */
public enum ExpertiseLevel {
    L1,  // Beginner/Learning
    L2,  // Basic Competency
    L3,  // Intermediate/Skilled
    L4,  // Advanced/Expert
    L5   // Master/Specialist
}
